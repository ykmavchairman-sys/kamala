// Current live indicative gold rate per gram (INR) - matching Ballari benchmark & IBJA standard
export const LIVE_GOLD_RATES = {
  rate24KPerGram: 14641,
  rate22KPerGram: 13411,
  rate18KPerGram: 10981,
  rateSilverPerGram: 209.5,
  lastUpdated: 'Live IBJA Benchmark (ibjarates.com) • Ballari Sarafa',
};

export function calculateGoldPrice(product: GoldProduct): {
  goldCost: number;
  makingCost: number;
  gstAmount: number;
  totalPrice: number;
} {
  let rate = LIVE_GOLD_RATES.rate22KPerGram;
  if (product.goldPurityKarat === 24) rate = LIVE_GOLD_RATES.rate24KPerGram;
  else if (product.goldPurityKarat === 18) rate = LIVE_GOLD_RATES.rate18KPerGram;
  else if (product.goldPurityKarat === 0) rate = LIVE_GOLD_RATES.rateSilverPerGram;

  const goldCost = Math.round(product.weightGrams * rate);
  const makingCost = Math.round((goldCost * product.makingChargePercent) / 100);
  const subtotal = goldCost + makingCost;
  const gstAmount = Math.round(subtotal * 0.03); // 3% standard Indian GST on precious metal jewelry
  const totalPrice = Math.round((subtotal + gstAmount) / 100) * 100;
  return { goldCost, makingCost, gstAmount, totalPrice };
}

